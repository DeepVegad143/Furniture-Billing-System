import mongoose from 'mongoose';

const customerSchema = new mongoose.Schema(
  {
    ownerId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
      index: true,
    },
    name: {
      type: String,
      required: true,
      trim: true,
    },
    phone: {
      type: String,
      required: true,
      trim: true,
    },
    address: {
      type: String,
      default: '',
      trim: true,
    },
    notes: {
      type: String,
      default: '',
      trim: true,
    },
  },
  {
    timestamps: true,
  }
);

// Compound index for fast owner lookups and searching
customerSchema.index({ ownerId: 1, name: 1 });
customerSchema.index({ ownerId: 1, phone: 1 });

export const Customer = mongoose.model('Customer', customerSchema);
